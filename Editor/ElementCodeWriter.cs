using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using MVVM.UGUI.Elements.Core;

namespace MVVM.UGUI.Editor
{
    /// <summary>View 의 partial `.g.cs` 내용을 만든다 — 숨은 Element 배열 + 타입 있는 속성.</summary>
    public static class ElementCodeWriter
    {
        /// <summary>생성된 partial 이 선언하는 직렬화 배열 이름. 프리팹에 이 이름으로 저장되므로 바꾸면 참조가 끊긴다.</summary>
        public const string ArrayField = "generatedElements";

        public static string FileName(Type viewType) => viewType.Name + ".Elements.g.cs";

        public static string Write(Type viewType, IReadOnlyList<Element> elements, IReadOnlyList<string> names)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// MVVM UGUI Element 속성 생성기가 만든 파일 — 손대지 않는다.\n");
            sb.Append("// 프리팹을 저장할 때 · 인스펙터의 \"Element 속성 생성\" 버튼으로 다시 만든다.\n");
            sb.Append("// </auto-generated>\n");

            bool hasNamespace = !string.IsNullOrEmpty(viewType.Namespace);
            string indent = hasNamespace ? "    " : "";
            if (hasNamespace)
                sb.Append("namespace ").Append(viewType.Namespace).Append("\n{\n");

            sb.Append(indent).Append("partial class ").Append(viewType.Name).Append('\n');
            sb.Append(indent).Append("{\n");
            sb.Append(indent).Append("    [global::UnityEngine.SerializeField, global::UnityEngine.HideInInspector]\n");
            sb.Append(indent).Append("    private ").Append(TypeName(typeof(Element))).Append("[] ").Append(ArrayField).Append(";\n");

            if (elements.Count > 0)
                sb.Append('\n');

            for (int i = 0; i < elements.Count; i++)
            {
                string type = TypeName(elements[i].GetType());
                sb.Append(indent).Append("    private ").Append(type).Append(' ').Append(names[i])
                  .Append(" => (").Append(type).Append(')').Append(ArrayField).Append('[').Append(i).Append("];\n");
            }

            sb.Append(indent).Append("}\n");
            if (hasNamespace)
                sb.Append("}\n");
            return sb.ToString();
        }

        /// <summary>C# 코드에 쓸 전체 이름 (`global::` · 중첩 타입 · 제네릭 포함).</summary>
        public static string TypeName(Type type)
        {
            if (type.IsGenericParameter)
                return type.Name;

            string name = type.Name;
            int tick = name.IndexOf('`');
            if (tick >= 0)
                name = name.Substring(0, tick);

            string owner = type.IsNested
                ? TypeName(type.DeclaringType)
                : "global::" + (string.IsNullOrEmpty(type.Namespace) ? "" : type.Namespace + ".");
            string full = type.IsNested ? owner + "." + name : owner + name;

            if (!type.IsGenericType)
                return full;

            var args = type.GetGenericArguments().Select(TypeName);
            return full + "<" + string.Join(", ", args) + ">";
        }
    }
}
